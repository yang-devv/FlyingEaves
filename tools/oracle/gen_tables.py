"""Write src/main/java/com/flyingeaves/gen/Tables.java: the generator's data tables taken straight from the Python
modules (so they cannot drift by hand-copying): furniture.ROOMS (with EXTRAS), the code pieces' sizes, CLEARANCE,
furniture_big.LAYOUTS / CENTER_PIECE, bgen.K (the kinds, sites.py's included), compose's option lists.

python -I tools/oracle/gen_tables.py
"""
import os
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
GEN = ROOT / "generator"
OUT = ROOT / "src" / "main" / "java" / "com" / "flyingeaves" / "gen" / "Tables.java"


def j(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return f"{v}"
    if isinstance(v, float):
        return f"{v!r}d"
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, dict):
        return "m(" + ", ".join(f"{j(k)}, {j(x)}" for k, x in v.items()) + ")"
    if isinstance(v, (list, tuple)):
        return "l(" + ", ".join(j(x) for x in v) + ")"
    if isinstance(v, (set, frozenset)):
        return "l(" + ", ".join(j(x) for x in sorted(v)) + ")"
    raise TypeError(type(v))


def main():
    os.environ["FLYINGEAVES_RUN"] = tempfile.mkdtemp(prefix="fe_tables_")
    sys.path.insert(0, str(GEN))
    import furniture as FU
    import furniture_big as FB
    import bgen
    import sites  # noqa: F401  (registers the special-site kinds into bgen.K)
    import compose
    code_sizes = {}
    import parts
    templ = parts.load()
    for name, (fn, w, d) in FU.PIECES.items():
        if name not in templ:
            code_sizes[name] = [w, d]
    tables = dict(
        FURN_ROOMS=FU.ROOMS, CODE_PIECES=code_sizes, CLEARANCE=FU.CLEARANCE, LAYOUTS=FB.LAYOUTS, CENTER_PIECE=FB.CENTER_PIECE,
        KINDS=bgen.K, COMPANIONS=compose.COMPANIONS, SHOP_USES=list(compose.SHOP_USES),
        PRIVATE_ROOMS=sorted(bgen.PRIVATE_ROOMS), CLOSED_ROOMS=sorted(bgen.CLOSED_ROOMS),
    )
    lines = ["package com.flyingeaves.gen;", "", "import java.util.ArrayList;", "import java.util.LinkedHashMap;", "import java.util.List;",
             "import java.util.Map;", "", "/** Generated by tools/oracle/gen_tables.py from the Python generator - do not edit by hand. */",
             "@SuppressWarnings(\"unchecked\")", "public final class Tables {", "    private Tables() {", "    }", "",
             "    static Map<String, Object> m(Object... kv) {", "        Map<String, Object> m = new LinkedHashMap<>();",
             "        for (int i = 0; i < kv.length; i += 2) m.put((String) kv[i], kv[i + 1]);", "        return m;", "    }", "",
             "    static List<Object> l(Object... a) {", "        return new ArrayList<>(List.of(a));", "    }", ""]
    for name, val in tables.items():
        if isinstance(val, dict) and len(val) > 40:        # (big maps: one put per line, in methods, for the 64 KB limit)
            lines.append(f"    public static final Map<String, Object> {name} = new LinkedHashMap<>();")
            lines.append("")
            items = list(val.items())
            for c in range(0, len(items), 20):
                lines.append(f"    private static void {name.lower()}{c // 20}() {{")
                for k, x in items[c:c + 20]:
                    lines.append(f"        {name}.put({j(k)}, {j(x)});")
                lines.append("    }")
                lines.append("")
            lines.append("    static {")
            for c in range(0, len(items), 20):
                lines.append(f"        {name.lower()}{c // 20}();")
            lines.append("    }")
            lines.append("")
        else:
            typ = "Map<String, Object>" if isinstance(val, dict) else "List<Object>"
            lines.append(f"    public static final {typ} {name} = {j(val)};")
            lines.append("")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT, sum(len(v) for v in tables.values()), "entries")


if __name__ == "__main__":
    main()
